#!/usr/bin/env python3
"""Generate exact Git provenance; fail instead of silently embedding an unknown SHA."""
from pathlib import Path
import subprocess

repo = Path(__file__).resolve().parent.parent
commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=repo, text=True).strip()
if len(commit) != 40 or any(c not in '0123456789abcdef' for c in commit):
    raise SystemExit('Cannot obtain firmware Git SHA')
dirty = bool(subprocess.check_output(['git', 'status', '--porcelain'], cwd=repo, text=True).strip())
header = repo / 'LapTune/Core/Inc/build_info.h'
text = ('/* Generated by tools/write_build_info.py; do not edit. */\n'
        f'#define FIRMWARE_COMMIT "{commit}"\n#define FIRMWARE_DIRTY {int(dirty)}\n')
if not header.exists() or header.read_text() != text:
    header.write_text(text)
print(f'Firmware SHA {commit}; dirty={dirty}')
